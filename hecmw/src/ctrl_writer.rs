use fem_core::FrontistrControlSettings;
use std::{fmt::Write as FmtWrite, io, path::Path};

pub struct HecmwCtrlParams<'a> {
    pub mesh_name: &'a str,
    pub cnt_name: &'a str,
    pub result_name: &'a str,
}

pub fn write_hecmw_ctrl(dir: impl AsRef<Path>, p: &HecmwCtrlParams<'_>) -> io::Result<()> {
    write_hecmw_ctrl_with_settings(dir, p, FrontistrControlSettings::default())
}

pub fn write_hecmw_ctrl_with_settings(
    dir: impl AsRef<Path>,
    p: &HecmwCtrlParams<'_>,
    settings: FrontistrControlSettings,
) -> io::Result<()> {
    let path = dir.as_ref().join("hecmw_ctrl.dat");
    let mut out = String::new();
    writeln!(out, "#\n# Generated by bevyistr\n#").unwrap();
    writeln!(
        out,
        "!MESH, NAME=fstrMSH, TYPE=HECMW-ENTIRE\n {}.msh",
        p.mesh_name
    )
    .unwrap();
    writeln!(out, "!CONTROL, NAME=fstrCNT\n {}.cnt", p.cnt_name).unwrap();
    write_result_controls(&mut out, p, settings);
    std::fs::write(path, out.as_bytes())
}

/// Controls for the official two-stage MPI workflow: partition the entire
/// mesh, then solve the distributed mesh. The caller owns `distributed_name`
/// and must not reuse stale partition files.
pub fn write_parallel_hecmw_ctrl(
    dir: impl AsRef<Path>,
    p: &HecmwCtrlParams<'_>,
    distributed_name: &str,
    ranks: u16,
) -> io::Result<()> {
    write_parallel_hecmw_ctrl_with_settings(
        dir,
        p,
        distributed_name,
        ranks,
        FrontistrControlSettings::default(),
    )
}

pub fn write_parallel_hecmw_ctrl_with_settings(
    dir: impl AsRef<Path>,
    p: &HecmwCtrlParams<'_>,
    distributed_name: &str,
    ranks: u16,
    settings: FrontistrControlSettings,
) -> io::Result<()> {
    if ranks == 0
        || [p.mesh_name, p.cnt_name, p.result_name, distributed_name]
            .iter()
            .any(|name| !crate::staged_inputs::is_project_name(name))
    {
        return Err(io::Error::new(
            io::ErrorKind::InvalidInput,
            "Invalid parallel project name or domain count",
        ));
    }
    let mut out = String::from("# Generated by bevyistr: partition first, then solve\n");
    writeln!(
        out,
        "!MESH, NAME=part_in, TYPE=HECMW-ENTIRE\n {}.msh",
        p.mesh_name
    )
    .unwrap();
    writeln!(
        out,
        "!MESH, NAME=part_out, TYPE=HECMW-DIST\n {distributed_name}"
    )
    .unwrap();
    writeln!(
        out,
        "!MESH, NAME=fstrMSH, TYPE=HECMW-DIST\n {distributed_name}"
    )
    .unwrap();
    writeln!(out, "!CONTROL, NAME=fstrCNT\n {}.cnt", p.cnt_name).unwrap();
    write_result_controls(&mut out, p, settings);
    let staged = crate::staged_inputs::StagedInputs::new(dir.as_ref())?;
    std::fs::write(
        staged.path().join("hecmw_part_ctrl.dat"),
        format!("!PARTITION, TYPE=NODE-BASED, METHOD=PMETIS, DOMAIN={ranks}\n"),
    )?;
    std::fs::write(staged.path().join("hecmw_ctrl.dat"), out)?;
    staged.publish(&["hecmw_part_ctrl.dat", "hecmw_ctrl.dat"])
}

fn write_result_controls(
    out: &mut String,
    p: &HecmwCtrlParams<'_>,
    settings: FrontistrControlSettings,
) {
    write!(out, "!RESULT, NAME=fstrRES, IO=OUT").unwrap();
    if let Some(binary) = settings.binary_result {
        write!(out, ", TYPE={}", if binary { "BINARY" } else { "TEXT" }).unwrap();
    }
    writeln!(out, "\n {}.res", p.result_name).unwrap();
    writeln!(out, "!RESULT, NAME=vis_out, IO=OUT\n {}_vis", p.result_name).unwrap();
    if let Some(subdir) = settings.subdirectories {
        write!(out, "!SUBDIR,{}", if subdir.enabled { "ON" } else { "OFF" }).unwrap();
        if let Some(limit) = subdir.limit {
            write!(out, ",LIMIT={limit}").unwrap();
        }
        writeln!(out).unwrap();
    }
}

pub fn partition_mesh_path(
    directory: &Path,
    prefix: &str,
    ranks: u16,
    rank: u16,
    subdirectory_limit: Option<u32>,
) -> std::path::PathBuf {
    let mut path = directory.to_path_buf();
    if let Some(limit) = subdirectory_limit {
        path.push("MESH");
        if u32::from(ranks) > limit {
            path.push(format!("TRUNK{}", u32::from(rank) / limit));
        }
    }
    path.join(format!("{prefix}.{rank}"))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn retains_result_file_format_and_subdirectories() {
        let directory = tempfile::tempdir().unwrap();
        let settings = FrontistrControlSettings {
            binary_result: Some(true),
            subdirectories: Some(fem_core::FrontistrSubdirectories {
                enabled: true,
                limit: std::num::NonZeroU32::new(8000),
            }),
        };
        let params = HecmwCtrlParams {
            mesh_name: "new",
            cnt_name: "new",
            result_name: "new",
        };
        write_hecmw_ctrl_with_settings(directory.path(), &params, settings).unwrap();
        let reloaded = crate::load_hecmw_ctrl(directory.path().join("hecmw_ctrl.dat")).unwrap();
        assert_eq!(reloaded.settings, settings);
        assert!(reloaded.import_issues.is_empty());
        assert_eq!(reloaded.result_path.as_deref(), Some("new.res"));
    }
}
